#!/bin/bash
# ============================================================
# AI-architecture — 危险文件操作拦截
# 触发时机：PreToolUse (Bash)
# 作用：在 Bash 命令执行前检查是否包含危险操作
# 返回值：exit 0 = 放行, exit 2 = 阻断（exit 1 不阻断！）
# ============================================================

INPUT=$(cat)
CMD=$(echo "$INPUT" | python -c "
import sys, json
d = json.load(sys.stdin)
print(d.get('tool_input', {}).get('command', ''))
" 2>/dev/null)

# ============================================================
# 危险等级1：拦截对关键目录的批量删除/覆盖操作
# 项目尚未定义关键目录 — 待项目结构确定后填充
# 格式：'rm[[:space:]]+-rf.*<目录名>'
# ============================================================
DANGEROUS_PATTERNS=(
    # 示例：'rm[[:space:]]+-rf.*\.claude'
)

for pattern in "${DANGEROUS_PATTERNS[@]}"; do
    if echo "$CMD" | grep -qiE "$pattern"; then
        echo "🛑 危险操作拦截" >&2
        echo "=========================================" >&2
        echo "检测到对关键目录的批量删除操作" >&2
        echo "命令: $CMD" >&2
        echo "=========================================" >&2
        echo "项目关键目录不可批量删除，请逐文件确认后操作" >&2
        echo "如确实需要清理，请使用 git rm 逐文件删除并提交记录" >&2
        exit 2
    fi
done

# ============================================================
# 危险等级2：拦截强制推送到主分支
# ============================================================
if echo "$CMD" | grep -qiE 'git[[:space:]]+push[[:space:]]+.*(--force|-f)'; then
    if echo "$CMD" | grep -qiE '(master|main)'; then
        echo "🛑 危险操作拦截" >&2
        echo "=========================================" >&2
        echo "检测到对 master/main 分支的强制推送" >&2
        echo "命令: $CMD" >&2
        echo "=========================================" >&2
        echo "禁止强制推送到主分支，请使用正常推送或在分支上操作" >&2
        exit 2
    fi
fi

# ============================================================
# 项目特定警告规则 — 暂无
# ============================================================

exit 0
